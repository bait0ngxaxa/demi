// Builds the logo embedded in the centre of every DEMI QR code.
//
//   npm run qr:logo                         regenerate src/lib/qr/demi-qr-logo.ts from the committed 160 px PNG
//   npm run qr:logo -- --from <icon.png>    re-crop the mark from a full app icon first, then regenerate
//
// The QR pages cannot load the logo by URL (the activation-slips CSP is `img-src data:` and an SVG shown
// through <img> cannot fetch anything), so the PNG is inlined as base64 in a generated module.
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const masterPath = path.join(root, "docs/brand/demi-qr-logo-512.png");
const embeddedPngPath = path.join(root, "src/lib/qr/assets/demi-qr-logo-160.png");
const modulePath = path.join(root, "src/lib/qr/demi-qr-logo.ts");

const MASTER_SIZE = 512;
const EMBEDDED_SIZE = 160;
const PADDING_RATIO = 0.14;
const CORNER_RATIO = 0.2;
// Pixels whose darkest channel is below this belong to the mark; the icon's pale frame and its white
// background are lighter, so they fall outside the crop.
const MARK_CHANNEL_THRESHOLD = 200;

async function findMarkBounds(source) {
  const { data, info } = await sharp(source).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  let left = info.width;
  let top = info.height;
  let right = -1;
  let bottom = -1;
  for (let y = 0; y < info.height; y += 1) {
    for (let x = 0; x < info.width; x += 1) {
      const offset = (y * info.width + x) * info.channels;
      if (Math.min(data[offset], data[offset + 1], data[offset + 2]) >= MARK_CHANNEL_THRESHOLD) continue;
      left = Math.min(left, x);
      top = Math.min(top, y);
      right = Math.max(right, x);
      bottom = Math.max(bottom, y);
    }
  }
  if (right < 0) throw new Error("No logo mark found in the source image");
  return { left, top, width: right - left + 1, height: bottom - top + 1 };
}

async function buildMaster(source) {
  const bounds = await findMarkBounds(source);
  const inner = Math.round(MASTER_SIZE * (1 - 2 * PADDING_RATIO));
  const mark = await sharp(source)
    .extract(bounds)
    .resize(inner, inner, { fit: "contain", background: { r: 255, g: 255, b: 255, alpha: 0 } })
    .png()
    .toBuffer();
  const radius = Math.round(MASTER_SIZE * CORNER_RATIO);
  const tile = Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${MASTER_SIZE}" height="${MASTER_SIZE}">` +
      `<rect width="${MASTER_SIZE}" height="${MASTER_SIZE}" rx="${radius}" fill="#fff"/></svg>`,
  );
  const offset = Math.round((MASTER_SIZE - inner) / 2);
  await sharp(tile).composite([{ input: mark, left: offset, top: offset }]).png().toFile(masterPath);
}

async function buildEmbeddedPng() {
  await sharp(masterPath)
    .resize(EMBEDDED_SIZE, EMBEDDED_SIZE)
    .png({ palette: true, colors: 128, effort: 10, compressionLevel: 9 })
    .toFile(embeddedPngPath);
}

async function writeModule() {
  const png = await readFile(embeddedPngPath);
  const sha256 = createHash("sha256").update(png).digest("hex");
  const source = `// Generated by scripts/generate-qr-logo.mjs from src/lib/qr/assets/demi-qr-logo-160.png. Do not edit.
// Run \`npm run qr:logo\` after changing the PNG.

export const DEMI_QR_LOGO_PNG_SHA256 = "${sha256}";

export const DEMI_QR_LOGO_PNG_BASE64 =
  "${png.toString("base64")}";
`;
  await writeFile(modulePath, source, "utf8");
  return { bytes: png.length, sha256 };
}

const fromIndex = process.argv.indexOf("--from");
if (fromIndex !== -1) {
  const source = process.argv[fromIndex + 1];
  if (!source) throw new Error("--from needs the path of the full app icon PNG");
  await buildMaster(path.resolve(source));
  await buildEmbeddedPng();
}
const result = await writeModule();
console.log(`Wrote ${path.relative(root, modulePath)} (${result.bytes} bytes, sha256 ${result.sha256})`);
