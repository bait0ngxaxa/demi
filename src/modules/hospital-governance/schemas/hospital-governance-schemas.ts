import { z } from "zod";

export const hospitalGovernanceHospitalIdSchema = z.uuid();
export const hospitalGovernanceExpectedUpdatedAtSchema = z.iso.datetime({ offset: true });

export const hospitalGovernanceMutationSchema = z
  .object({
    hospitalId: hospitalGovernanceHospitalIdSchema,
    expectedUpdatedAt: hospitalGovernanceExpectedUpdatedAtSchema,
  })
  .strict();

export type HospitalGovernanceMutationInput = z.infer<typeof hospitalGovernanceMutationSchema>;

export const hospitalNameSchema = z.string().trim().min(1).max(200);

// Stable Hospital code: uppercase letters/digits, then letters, digits, "-" or "_" (max 32).
const hospitalCodePattern = /^[A-Z0-9][A-Z0-9_-]{0,31}$/u;

// Optional: a blank code is generated by the service (the registrant types only the name).
export const optionalHospitalCodeSchema = z.preprocess(
  (value) => (typeof value === "string" && value.trim() === "" ? undefined : value),
  z.string().trim().toUpperCase().regex(hospitalCodePattern).optional(),
);

export const hospitalGovernanceCreateSchema = z
  .object({
    hospitalCode: optionalHospitalCodeSchema,
    name: hospitalNameSchema,
    // ADR-0015: network type is chosen in the same step; editable later.
    networkRole: z.enum(["PARENT", "CHILD"]),
    // N1-D5: generated by the form; a replay returns the Hospital it already created.
    submissionNonce: z.uuid(),
  })
  .strict();

export const hospitalGovernanceRenameSchema = hospitalGovernanceMutationSchema.extend({
  name: hospitalNameSchema,
});

const hospitalRetirementReasonSchema = z.string().trim().min(1).max(500);

// N1-D1: retire (PENDING_VERIFICATION -> RETIRED) and restore (RETIRED -> PENDING_VERIFICATION) need a reason.
export const hospitalGovernanceRetirementSchema = hospitalGovernanceMutationSchema.extend({
  reason: hospitalRetirementReasonSchema,
});

export type HospitalGovernanceRetirementInput = z.infer<typeof hospitalGovernanceRetirementSchema>;

export const HOSPITAL_BULK_RETIRE_LIMIT = 100;

// N1-D4: one shared reason, all-or-nothing.
export const hospitalGovernanceBulkRetireSchema = z
  .object({
    hospitalIds: z
      .array(hospitalGovernanceHospitalIdSchema)
      .min(1)
      .max(HOSPITAL_BULK_RETIRE_LIMIT)
      .refine((ids) => new Set(ids).size === ids.length),
    reason: hospitalRetirementReasonSchema,
  })
  .strict();

// O1-A: CSV text is re-parsed on the server at apply; confirmations name the similar-name rows by file line.
const bulkRegistrationCsvTextSchema = z.string().min(1).max(256 * 1024);

export const hospitalGovernanceBulkRegistrationPreviewSchema = z
  .object({ csvText: bulkRegistrationCsvTextSchema })
  .strict();

export const hospitalGovernanceBulkRegistrationApplySchema = z
  .object({
    csvText: bulkRegistrationCsvTextSchema,
    submissionNonce: z.uuid(),
    confirmedRowNumbers: z.array(z.number().int().min(2)).max(201),
  })
  .strict();
